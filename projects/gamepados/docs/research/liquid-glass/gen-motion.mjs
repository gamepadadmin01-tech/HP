#!/usr/bin/env node
/**
 * gen-motion.mjs — emit motion.css from spring physics.
 *
 *   node gen-motion.mjs > motion.css
 *
 * Apple's UI animates on springs. A cubic-bezier is monotonic and therefore
 * cannot reproduce overshoot-and-settle, which is the exact thing that makes
 * iOS motion feel alive. CSS linear() can encode any curve, so we solve the
 * damped-oscillator ODE and emit the samples.
 *
 * Published Apple parameters:
 *   .spring            response 0.55  dampingFraction 0.825
 *   .interactiveSpring response 0.15  dampingFraction 0.86
 * .smooth / .snappy / .bouncy: Apple documents the BEHAVIOUR (no overshoot /
 * slight / clearly visible) but not the numbers. Ours are fitted to reproduce
 * that behaviour and are labelled `fitted` so nobody mistakes them for spec.
 */

/** Unit step response of a damped harmonic oscillator. */
function springValue(t, response, z) {
  const wn = (2 * Math.PI) / response;
  if (Math.abs(z - 1) < 1e-6) return 1 - Math.exp(-wn * t) * (1 + wn * t);
  if (z < 1) {
    const wd = wn * Math.sqrt(1 - z * z);
    return 1 - Math.exp(-z * wn * t) *
      (Math.cos(wd * t) + (z * wn / wd) * Math.sin(wd * t));
  }
  const a = wn * (-z + Math.sqrt(z * z - 1));
  const b = wn * (-z - Math.sqrt(z * z - 1));
  return 1 - (b * Math.exp(a * t) - a * Math.exp(b * t)) / (b - a);
}

/** Time until it stays inside a 0.1% band around the target. */
function settleTime(response, z, cap = 6) {
  const dt = 1 / 1000;
  let last = 0;
  for (let t = 0; t <= cap; t += dt) {
    if (Math.abs(springValue(t, response, z) - 1) > 0.001) last = t;
  }
  return Math.min(cap, last + dt);
}

function peakOf(response, z, dur) {
  let peak = 0;
  for (let t = 0; t <= dur; t += 1 / 600) peak = Math.max(peak, springValue(t, response, z));
  return peak;
}

/** Sample to a CSS linear(). Biased toward the start where curvature is high. */
function toLinear(response, z, dur, stops = 42) {
  const pts = [];
  for (let i = 0; i <= stops; i++) {
    const p = i / stops;
    const eased = Math.pow(p, 0.85);
    pts.push([eased, springValue(eased * dur, response, z)]);
  }
  pts[0][1] = 0;
  pts[pts.length - 1][1] = 1;
  return 'linear(' + pts.map(([p, v]) => `${v.toFixed(4)} ${(p * 100).toFixed(2)}%`).join(', ') + ')';
}

const PRESETS = [
  { key: 'ios-spring',      label: '.spring',            src: 'Apple published', r: 0.55, z: 0.825 },
  { key: 'ios-interactive', label: '.interactiveSpring', src: 'Apple published', r: 0.15, z: 0.86 },
  { key: 'ios-smooth',      label: '.smooth',            src: 'fitted — critically damped, no overshoot', r: 0.40, z: 1.0 },
  { key: 'ios-snappy',      label: '.snappy',            src: 'fitted — slight overshoot', r: 0.35, z: 0.85 },
  { key: 'ios-bouncy',      label: '.bouncy',            src: 'fitted — visible overshoot', r: 0.45, z: 0.65 },
];

const rows = PRESETS.map(p => {
  const settle = settleTime(p.r, p.z);
  const dur = Math.min(settle, 1.6);
  const overshoot = peakOf(p.r, p.z, dur) - 1;
  return { ...p, settle, dur, overshoot, css: toLinear(p.r, p.z, dur) };
});

const out = `/* motion.css — Apple-equivalent spring easings.
   GENERATED by gen-motion.mjs from the damped-oscillator equation. Do not
   hand-edit; regenerate instead.

   Why linear() and not cubic-bezier: a bezier is monotonic, so it cannot
   overshoot and settle. That settle is what makes iOS motion feel alive.

${rows.map(r => ` *   ${r.label.padEnd(19)} response ${r.r}  damping ${r.z}  ` +
  `overshoot ${r.overshoot > 0.001 ? (r.overshoot * 100).toFixed(1) + '%' : 'none'}  ` +
  `settles ${(r.settle * 1000).toFixed(0)}ms   (${r.src})`).join('\n')}
*/
:root{
${rows.map(r => `  --ease-${r.key}: ${r.css};\n  --dur-${r.key}: ${r.dur.toFixed(3)}s;`).join('\n')}

  /* Closest monotonic approximation, used where linear() is unavailable. */
  --ease-fallback: cubic-bezier(.32,.72,0,1);
}

/* Older WebViews (minSdk 24 territory) have no linear(). Degrade, don't break. */
@supports not (transition-timing-function: linear(0, 1)){
  :root{
${rows.map(r => `    --ease-${r.key}: var(--ease-fallback);`).join('\n')}
  }
}

/* Reduce Motion means none, not less. */
@media (prefers-reduced-motion: reduce){
  *, *::before, *::after{
    animation-duration: .01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: .01ms !important;
    scroll-behavior: auto !important;
  }
}

/* ── usage ────────────────────────────────────────────────────────────────
   press / toggle      -> --ease-ios-interactive  (210ms, barely overshoots)
   sheet + nav         -> --ease-ios-smooth       (no overshoot, never fussy)
   selection, chips    -> --ease-ios-snappy
   celebratory only    -> --ease-ios-bouncy       (6.8% overshoot; use sparingly)
   general purpose     -> --ease-ios-spring       (Apple's own default)

   NEVER put these on a pad widget. Gameplay feedback is 100ms linear on
   background only — see CLAUDE.md §1.
   ──────────────────────────────────────────────────────────────────────── */
`;

process.stdout.write(out);
