// Builds the "golden" file that holds the page's maths and the phone engine's maths equal.
// controller-ui writes it (node gen-golden.mjs); android-client reads it (ParityGoldenTest.kt) and must get the
// same numbers. touchpad-fuzz.test.mjs fails if the file is out of date, so the page side cannot change
// without regenerating it, and the Android test then fails if the phone side has not followed.
import { TouchpadState } from "./src/app/touchpad.ts";
import { stickResponse } from "./src/app/stickFeel.ts";

const rng = (seed) => () => { seed |= 0; seed = (seed + 0x6D2B79F5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
const r2 = (v) => Math.round(v * 100) / 100;
const f9 = (v) => (Object.is(v, -0) ? 0 : v).toFixed(9);

export function buildGolden() {
  const out = [];
  out.push("# generated by controller-ui/gen-golden.mjs: do not edit by hand");
  for (const feel of ["speed", "distance"]) for (const release of ["instant", "glide"]) for (const sens of [0.3, 1, 3]) for (const seed of [11, 22, 33]) {
    const r = rng(seed * 7919 + sens * 100 + (feel === "speed" ? 1 : 2) + (release === "glide" ? 5 : 0));
    const s = new TouchpadState(feel, release, sens);
    out.push(`P ${feel} ${release} ${sens}`);
    let t = 1000, x = 200, y = 120, down = false;
    for (let i = 0; i < 70; i++) {
      t += r() < 0.1 ? 0 : 1 + Math.floor(r() * 30);              // sometimes the same millisecond
      const roll = r();
      let op;
      if (!down) { op = roll < 0.7 ? "d" : "k"; } else if (roll < 0.55) op = "m"; else if (roll < 0.8) op = "k"; else if (roll < 0.93) op = "u"; else if (roll < 0.97) op = "r"; else op = "k";
      if (op === "d") { x = r2(50 + r() * 300); y = r2(30 + r() * 180); s.down(x, y, t); down = true; }
      else if (op === "m") { const big = r() < 0.1; x = r2(x + (r() - 0.5) * (big ? 600 : 50)); y = r2(y + (r() - 0.5) * (big ? 400 : 34)); s.move(x, y, t); }
      else if (op === "k") s.tick(t);
      else if (op === "u") { s.up(t); down = false; }
      else { s.reset(); down = false; }
      out.push(`${op} ${t} ${op === "d" || op === "m" ? x : 0} ${op === "d" || op === "m" ? y : 0} = ${f9(s.x)} ${f9(s.y)} ${s.active ? 1 : 0}`);
    }
    out.push("E");
  }
  const pts = [-60, -45, -30, -12, -5, -4.8, 0, 3, 4.79, 4.81, 10, 30, 45, 60];
  for (const exp of [1, 1.6]) for (const gain of [0.2, 0.5, 0.75, 1, 1.5, 2]) for (const x of pts) for (const y of pts) {
    if (Math.hypot(x, y) > 60.0001) continue;                     // the caller keeps a stick inside its circle
    const o = stickResponse(x, y, gain, exp);
    out.push(`S ${x} ${y} ${gain} ${exp} = ${f9(o.x)} ${f9(o.y)}`);
  }
  return out.join("\n") + "\n";
}
