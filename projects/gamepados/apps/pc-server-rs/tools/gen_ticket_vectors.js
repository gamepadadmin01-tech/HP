// Generates tests/ticket_vectors.json from the REAL backend issuer.
//
//   node tools/gen_ticket_vectors.js
//
// Mirrors tools/gen_golden.py, which produced the GRX vectors from the real
// Python server. The point is the same: the Rust verifier is checked against
// bytes the actual issuer produced, so the two implementations cannot drift
// apart silently. A format change on either side fails a test instead of
// rejecting every ticket in the field.
//
// The seed is FIXED so the output is deterministic and can be committed. It is
// a test key and must never be used for anything.

const fs = require('fs');
const path = require('path');

const SEED = '07'.repeat(32);
process.env.SESSION_TICKET_ED25519_PRIVATE_KEY = SEED;

const ticket = require('../../../website/backend/billing/ticket.js');

const at = (iso) => new Date(iso);
const cases = [
  { desc: 'typical heartbeat ticket',
    sessionId: '3f2504e0-4f89-11d3-9a0c-0305e82c3301', fence: 1, seq: 1, ttlSeconds: 180 },
  { desc: 'later sequence, same session',
    sessionId: '3f2504e0-4f89-11d3-9a0c-0305e82c3301', fence: 1, seq: 2, ttlSeconds: 180 },
  { desc: 'fence bumped by a takeover',
    sessionId: '3f2504e0-4f89-11d3-9a0c-0305e82c3301', fence: 2, seq: 3, ttlSeconds: 180 },
  { desc: 'short ttl',
    sessionId: 'ffffffff-ffff-ffff-ffff-ffffffffffff', fence: 65535, seq: 65535, ttlSeconds: 1 },
  { desc: 'ttl above the servers cap, which must be clamped on verify',
    sessionId: '00000000-0000-0000-0000-000000000001', fence: 1, seq: 4, ttlSeconds: 65535 },
  { desc: 'large fence and seq near u32 range',
    sessionId: '12345678-9abc-def0-1234-56789abcdef0', fence: 4000000000, seq: 4000000001, ttlSeconds: 300 },
  { desc: 'non-uuid session id (hashed to 16 bytes)',
    sessionId: 'sess_not_a_uuid_at_all', fence: 3, seq: 5, ttlSeconds: 120 },
];

const out = {
  _comment: 'Generated by tools/gen_ticket_vectors.js from website/backend/billing/ticket.js. Do not hand-edit.',
  publicKeyHex: ticket.publicKeyHex(),
  ticketLen: ticket.TICKET_LEN,
  cases: cases.map((c) => ({
    ...c,
    sessionIdBytesHex: ticket.uuidToBytes(c.sessionId).toString('hex'),
    base64: ticket.issueTicket({ ...c, now: at('2026-08-18T12:00:00Z') }).toString('base64'),
  })),
};

const dest = path.join(__dirname, '..', 'tests', 'ticket_vectors.json');
fs.writeFileSync(dest, JSON.stringify(out, null, 2) + '\n');
console.log('wrote ' + dest + ' (' + out.cases.length + ' cases, key ' + out.publicKeyHex.slice(0, 16) + '...)');
